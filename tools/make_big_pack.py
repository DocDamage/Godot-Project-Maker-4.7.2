"""Generate a large synthetic pack for the performance tests (T10.08).

    python tools/make_big_pack.py --out build/big_pack [--count 1000]

The pack mixes tile sheets (16, 32 and 48 px grids, some with gutters), character strips and item
icons, all drawn by the synthetic-pack generators with deterministic variations so that no two
files have the same bytes. The same arguments always give the same pack.
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent


def _synthetic():
    spec = importlib.util.spec_from_file_location(
        "make_synthetic_packs", HERE / "make_synthetic_packs.py"
    )
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules.setdefault("make_synthetic_packs", module)
    spec.loader.exec_module(module)
    return module


def tile_sheet(syn, n: int) -> Image.Image:
    """A tile sheet with 4-9 columns/rows of 16, 32 or 48 px tiles; every 5th has a 1 px gutter."""
    size = (16, 32, 48)[n % 3]
    cols = 4 + n % 6
    rows = 3 + (n // 3) % 5
    gutter = 1 if n % 5 == 4 else 0
    step = size + gutter
    img = Image.new("RGBA", (cols * step - gutter, rows * step - gutter), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    for r in range(rows):
        for c in range(cols):
            syn._tile(d, c * step, r * step, size, size, n * 7 + r * cols + c, step=1 + n % 3)
    return img


def strip(syn, n: int) -> Image.Image:
    frames = 4 + n % 5
    side = 16 if n % 2 == 0 else 32
    return syn._strip(frames, n, side, side)


def icon(syn, n: int) -> Image.Image:
    img = syn._item_icon(n)
    if n % 4 == 3:
        img = img.resize((32, 32), Image.Resampling.NEAREST)
    # a deterministic mark makes every icon unique
    d = ImageDraw.Draw(img)
    d.point((n % img.width, (n // img.width) % img.height), fill=syn.pal(n))
    return img


def make_big_pack(out: Path, count: int = 1000) -> int:
    """Write ``count`` images (30% tile sheets, 30% strips, 40% icons); returns the count."""
    syn = _synthetic()
    out = Path(out)
    n_tiles = count * 3 // 10
    n_strips = count * 3 // 10
    n_icons = count - n_tiles - n_strips
    plan = (
        ("tilesets", "tiles", n_tiles, tile_sheet),
        ("characters", "strip", n_strips, strip),
        ("icons", "icon", n_icons, icon),
    )
    for folder, stem, total, make in plan:
        target = out / folder
        target.mkdir(parents=True, exist_ok=True)
        for i in range(total):
            syn._save_png(make(syn, i), target / f"{stem}_{i:04d}.png")
    (out / "LICENSE.txt").write_text(
        "CC0-1.0: generated by tools/make_big_pack.py\n", encoding="utf-8"
    )
    return count


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--count", type=int, default=1000)
    args = parser.parse_args(argv)
    print(f"wrote {make_big_pack(args.out, args.count)} images to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
